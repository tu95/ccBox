import Foundation

func applyChromeWebLanguage(
    to browserProfile: URL,
    environmentName: String,
    acceptLanguages: String = "en-US,en"
) throws {
    let defaultProfile = browserProfile.appendingPathComponent("Default", isDirectory: true)
    try makePrivateDirectory(defaultProfile)
    let preferencesURL = defaultProfile.appendingPathComponent("Preferences")
    var preferences: [String: Any] = [:]
    if let existingData = try? Data(contentsOf: preferencesURL),
       let existing = try? JSONSerialization.jsonObject(with: existingData) as? [String: Any] {
        preferences = existing
    }

    var intl = (preferences["intl"] as? [String: Any]) ?? [:]
    intl["accept_languages"] = acceptLanguages
    intl["selected_languages"] = acceptLanguages
    preferences["intl"] = intl

    var profile = (preferences["profile"] as? [String: Any]) ?? [:]
    profile["name"] = "Sandbox · \(environmentName)"
    preferences["profile"] = profile

    // Remove any previously injected custom theme color so Chrome keeps its native appearance.
    if var autogenerated = preferences["autogenerated"] as? [String: Any] {
        autogenerated.removeValue(forKey: "theme")
        preferences["autogenerated"] = autogenerated
    }
    if var browser = preferences["browser"] as? [String: Any] {
        browser.removeValue(forKey: "theme")
        preferences["browser"] = browser
    }

    let updated = try JSONSerialization.data(withJSONObject: preferences, options: [.sortedKeys])
    try writePrivate(updated, to: preferencesURL)
}
